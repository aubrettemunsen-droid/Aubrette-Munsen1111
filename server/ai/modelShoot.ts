import { ai, isGeminiConfigured, parseDataUrl } from './geminiClient.ts';
import { ModelShootParams } from '../../src/types/index.ts';

const STYLE_PROMPTS: Record<string, string> = {
  commercial_catalog: 'Clean e-commerce commercial catalog photography, sharp details, bright even softbox illumination, neutral posture, high conversion appeal.',
  high_fashion_editorial: 'High-end Vogue runway fashion editorial, dramatic directional chiaroscuro lighting, cinematic angle, sophisticated haute couture poise.',
  streetwear_lookbook: 'Contemporary urban streetwear lookbook, authentic street attitude, natural ambient light, dynamic candid posture.',
  minimalist_nordic: 'Scandinavian minimalist aesthetic, gentle diffuse morning window light, organic quiet luxury, muted earthy tones.'
};

const BACKGROUND_PROMPTS: Record<string, string> = {
  studio_warm_grey: 'Professional seamless warm grey cyclorama studio backdrop with soft floor cast shadows.',
  architectural_concrete: 'Minimalist brutalist architectural interior with raw polished concrete and subtle sunlight geometric cast lines.',
  sunlit_loft: 'Modern open industrial loft with tall warehouse windows, wooden flooring, and warm natural sunlight.',
  outdoor_urban: 'Refined metropolitan European city street corner with blurred neoclassical stone facades and elegant cobblestones.'
};

const POSE_PROMPTS: Record<string, string> = {
  natural_standing: 'Relaxed natural standing pose facing slightly towards the camera, weight shifted gracefully, arms natural.',
  walking_motion: 'Confident stride in motion, subtle fabric movement and dynamic flow, realistic step.',
  relaxed_seated: 'Relaxed seated posture on a minimalist sculptural bench, showing natural draping of the garment.'
};

export async function executeModelShoot(params: {
  garmentDataUrl: string;
  options: ModelShootParams;
}): Promise<{
  resultDataUrls: string[];
  modelUsed: string;
  tokensEstimate: number;
}> {
  const { garmentDataUrl, options } = params;

  if (!isGeminiConfigured) {
    throw new Error('GEMINI_API_KEY is not configured on the server.');
  }

  const garmentParsed = parseDataUrl(garmentDataUrl);

  const styleText = STYLE_PROMPTS[options.modelStyle] || STYLE_PROMPTS.commercial_catalog;
  const bgText = BACKGROUND_PROMPTS[options.background] || BACKGROUND_PROMPTS.studio_warm_grey;
  const poseText = POSE_PROMPTS[options.pose] || POSE_PROMPTS.natural_standing;

  const promptText = `Commercial Fashion Model Shoot from Apparel Reference:
Reference image is the exact apparel garment.

Task Requirements:
1. Generate an attractive, professional fashion model (${options.gender} model) wearing this EXACT reference garment.
2. Clothing Consistency (HIGHEST PRIORITY):
   - Faithfully retain the garment's precise silhouette, neckline/collar design, sleeve construction, buttons, zippers, pockets, and fabric weave.
   - Do NOT invent fake brands, logos, or arbitrary graphics.
   - Preserve the exact color shades, sheen, and textile weight of the reference piece.
3. Shot Specifications:
   - Framing: ${options.composition.replace('_', ' ')}.
   - Photography Style: ${styleText}
   - Setting: ${bgText}
   - Model Pose: ${poseText}
4. Ensure anatomical precision: flawless hands, natural skin pores, realistic hair strands, and anatomically correct proportions.
5. High-end commercial fashion quality, 8k resolution look, no digital distortion or plastic blur.`;

  const targetModel = 'gemini-nano-banana-2.1'; // Supports 1K, 2K, 4K

  const candidatesToGenerate = Math.min(Math.max(options.numCandidates || 1, 1), 2);
  const results: string[] = [];

  for (let i = 0; i < candidatesToGenerate; i++) {
    const response = await ai.models.generateContent({
      model: targetModel,
      contents: {
        parts: [
          {
            inlineData: {
              mimeType: garmentParsed.mimeType,
              data: garmentParsed.base64Data,
            },
          },
          {
            text: `${promptText} (Candidate variation ${i + 1})`,
          },
        ],
      },
      config: {
        imageConfig: {
          aspectRatio: options.composition === 'full_body' ? '3:4' : '1:1',
          imageSize: options.imageSize || '1K',
        },
      },
    });

    const candidate = response.candidates?.[0];
    if (candidate?.content?.parts) {
      for (const part of candidate.content.parts) {
        if (part.inlineData?.data) {
          const outMime = part.inlineData.mimeType || 'image/jpeg';
          results.push(`data:${outMime};base64,${part.inlineData.data}`);
          break;
        }
      }
    }
  }

  if (results.length === 0) {
    throw new Error('No candidate images generated by the fashion model synthesis model.');
  }

  return {
    resultDataUrls: results,
    modelUsed: `${targetModel} (${options.imageSize} Commercial Model Synthesis)`,
    tokensEstimate: candidatesToGenerate * 1600,
  };
}
